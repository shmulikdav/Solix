#!/usr/bin/env node
/**
 * `docs/CLAIMS.md` → `packages/cli/claims.json`.
 *
 * The ledger binds each claim to a test *in this repo*. The website repo
 * makes the same claims and cannot see this code at all, which is how
 * "wrap it with `solix run` and it gets the same treatment" shipped to the
 * home page while `run.ts` and `CLAIM-RUN-UNGATED` said the opposite.
 *
 * So the ledger is published as data. The site vendors this file and a test
 * there refuses any governance claim that does not cite an id present in
 * it — which means a sentence about the gate cannot be written over there
 * without naming the claim it depends on, and the canonical wording sits
 * next to the prose where a contradiction is visible.
 *
 * Shipped inside the npm package (`files` includes claims.json) so anything
 * that installs Solix can read what it promises.
 *
 * Usage:
 *   node scripts/emit-claims.mjs            # write it
 *   node scripts/emit-claims.mjs --check    # fail if the file is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const LEDGER = resolve(ROOT, 'docs/CLAIMS.md');
const PKG = resolve(ROOT, 'packages/cli/package.json');
const OUT = resolve(ROOT, 'packages/cli/claims.json');

/**
 * Rows of the ledger table. Exported so the test uses the same parser the
 * emitter does — two parsers would be two chances to disagree.
 */
export function parseLedger(markdown) {
  const rows = [];
  for (const line of markdown.split('\n')) {
    if (!line.startsWith('|')) continue;
    const cells = line
      .split('|')
      .slice(1, -1)
      .map((c) => c.trim());
    if (cells.length !== 4) continue;
    const id = cells[0].replace(/`/g, '');
    if (!id.startsWith('CLAIM-')) continue;
    rows.push({
      id,
      claim: cells[1],
      publishedIn: cells[2],
      heldBy: cells[3].replace(/`/g, ''),
    });
  }
  return rows;
}

export function buildManifest(markdown, version) {
  return {
    // The version these claims are true of. The site asserts this equals the
    // version it tells people to install, so bumping one forces the other.
    version,
    source: 'docs/CLAIMS.md',
    note:
      'Generated by scripts/emit-claims.mjs. Each claim is held by a test in ' +
      'the Solix repo; see heldBy. Do not edit by hand.',
    claims: parseLedger(markdown),
  };
}

function main() {
  const markdown = readFileSync(LEDGER, 'utf8');
  const { version } = JSON.parse(readFileSync(PKG, 'utf8'));
  const manifest = buildManifest(markdown, version);
  const json = `${JSON.stringify(manifest, null, 2)}\n`;

  if (process.argv.includes('--check')) {
    let current = null;
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== json) {
      console.error(
        '✗ packages/cli/claims.json is stale.\n' +
          '  Run: node scripts/emit-claims.mjs',
      );
      process.exit(1);
    }
    console.log(`✓ claims.json matches the ledger (${manifest.claims.length} claims)`);
    return;
  }

  writeFileSync(OUT, json);
  console.log(
    `✓ wrote packages/cli/claims.json — ${manifest.claims.length} claims at ${version}`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}

#!/usr/bin/env node
/**
 * Copy the advisor definitions into the Claude Code plugin.
 *
 * `packages/agents/*.md` is the source of truth — it is what `solix install`
 * writes into ~/.claude/agents. The plugin needs the same files present in
 * the repository, because a marketplace install reads them straight from
 * GitHub, so they are generated and committed rather than symlinked.
 *
 * `crew.sync.test.ts` fails when the two drift, which is the point: a plugin
 * quietly shipping last month's Sentinel would be worse than no plugin.
 */
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'packages', 'agents');
const DEST = join(ROOT, 'plugin', 'solix-crew', 'agents');

export function advisorFiles() {
  return readdirSync(SRC)
    .filter((f) => f.endsWith('.md'))
    .sort();
}

function sync() {
  rmSync(DEST, { recursive: true, force: true });
  mkdirSync(DEST, { recursive: true });
  const files = advisorFiles();
  for (const f of files) copyFileSync(join(SRC, f), join(DEST, f));
  writeFileSync(
    join(DEST, '.generated'),
    `Generated by scripts/sync-crew-plugin.mjs from packages/agents.\n` +
      `Edit the originals there; run \`pnpm sync:plugin\` to update these.\n`,
  );
  console.log(`synced ${files.length} advisors -> plugin/solix-crew/agents`);
}

if (import.meta.url === `file://${process.argv[1]}`) sync();
